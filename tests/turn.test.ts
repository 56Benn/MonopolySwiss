test("Bots spielen mit Bus, Auktionen ohne Frist und Bauregeln mehrere Runden ohne Blockade", () => {
  const bots = ["Einfach", "Mittel", "Schwer"].map((level, index) => player(`bot${index}`, `Bot ${index}`, index, level as "Einfach" | "Mittel" | "Schwer"));
  let s = newGame(bots[0]);
  s.players.push(bots[1], bots[2]);
  s.settings = { ...s.settings, dice: 3, perRound: true, limit: 0 };
  s = apply(s, "bot0", { type: "START" }, 0);
  let now = 1, stalled = 0;
  for (let step = 0; step < 4000 && s.phase !== "over" && s.round < 9; step++) {
    const next = advance(s, now);
    if (next === s) {
      now = Math.max(now + 500, s.deadline || now + 500);
      stalled++;
      assert.ok(stalled < 50, `Blockiert in Phase ${s.phase}`);
    } else stalled = 0;
    s = next;
    now += 300;
  }
  assert.ok(s.round >= 9 || s.phase === "over", `Nur Runde ${s.round}`);
  assert.ok(s.assets.some((asset) => asset.owner));
  for (const tile of s.assets) assert.ok(tile.levels.length <= 5);
  assert.ok(s.chat.every((message) => message.system || message.phrase));
});
