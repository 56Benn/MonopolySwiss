test("Casino: Bonus, Einladung, Teilnahme, Einsatzgrenze und genau eine Abrechnung", () => {
  let s = table();
  s.players[0].pos = 18;
  s = apply(s, "a", { type: "ROLL_DICE" }, 10, () => 0);
  s=tick(s,s.deadline);
  assert.equal(s.phase, "casinoInvite");
  assert.equal(s.players[0].cash, 510 * M);
  const invited=s.deadline;
  s = apply(s, "a", { type: "CASINO_ENTER" }, invited-9000);
  assert.equal(s.phase, "casinoInvite");
  assert.throws(() => apply(s, "b", { type: "CASINO_JOIN", yes: true }, invited-8000));
  s = tick(s, invited);
  assert.equal(s.phase, "casinoJoin");
  s = apply(s, "b", { type: "CASINO_JOIN", yes: true }, invited+100);
  s = apply(s, "a", { type: "CASINO_JOIN", yes: true }, invited+200);
  assert.equal(s.phase, "casinoBet");
  assert.deepEqual(s.casino?.seats, ["a", "b"]);
  assert.throws(() => apply(s, "b", { type: "PLACE_CASINO_BET", amount: 11 * M }, invited+300));
  assert.throws(() => apply(s, "a", { type: "PLACE_CASINO_BET", amount: 41 * M }, invited+300));
  s = apply(s, "a", { type: "PLACE_CASINO_BET", amount: 40 * M }, invited+400);
  assert.equal(s.players[0].cash, 470 * M);
  s = apply(s, "b", { type: "PLACE_CASINO_BET", amount: null }, invited+500, () => 1);
  assert.deepEqual(s.casino?.seats, ["a"]);
  while (s.phase === "blackjack") s = apply(s, s.casino!.hands[s.casino!.cursor].id, { type: "BLACKJACK_STAND" }, invited+600);
  assert.equal(s.phase, "casinoSettle");
  assert.equal(s.result?.hands.length, 1);
  const settled = s.players[0].cash;
  s = tick(s, s.deadline);
  assert.equal(s.phase, "manage");
  assert.equal(s.casino, null);
  assert.equal(s.players[0].cash, settled);
  assert.equal(s.extra, true);
  assert.throws(() => apply(s, "a", { type: "BLACKJACK_STAND" }));
});
